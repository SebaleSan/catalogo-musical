CREATE TABLE album (
    id_album NUMBER GENERATED BY DEFAULT AS IDENTITY,
    artist VARCHAR2(120 CHAR) NOT NULL,
    title VARCHAR2(150 CHAR) NOT NULL,
    year NUMBER(4),
    genre VARCHAR2(60 CHAR) NOT NULL,
    price NUMBER(19) NOT NULL,
    stock NUMBER(10) NOT NULL,
    cover_art VARCHAR2(255 CHAR),

    CONSTRAINT pk_album PRIMARY KEY (id_album)
);